// Map language display names to codes
const langNameToCode = {
    'English': 'en',
    'Hindi': 'hi',
    'Assamese': 'as',
    'Bengali': 'bn'
};

const langCodeToName = {
    'en': 'English',
    'hi': 'Hindi',
    'as': 'Assamese',
    'bn': 'Bengali'
};

// Date locale mapping
const langDateLocale = {
    'en': 'en-US',
    'hi': 'hi-IN',
    'as': 'as-IN',
    'bn': 'bn-IN'
};

/**
 * Apply translations to all elements with data-i18n attribute
 */
function applyTranslations(lang) {
    if (!translations[lang]) lang = 'en';
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Preserve child elements (like icons) by only replacing text nodes
            const childElements = Array.from(el.children);
            if (childElements.length > 0) {
                // Find text nodes and update them
                for (let node of el.childNodes) {
                    if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
                        node.textContent = translations[lang][key];
                        break;
                    }
                }
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });
}

/**
 * Set language and persist to localStorage
 */
function setLanguage(lang) {
    localStorage.setItem('selectedLang', lang);
    applyTranslations(lang);

    // Update all language selectors on the page
    document.querySelectorAll('.lang-selector').forEach(sel => {
        sel.value = langCodeToName[lang] || 'English';
    });

    // Update date display if present
    const datetimeEl = document.getElementById('datetime-display');
    if (datetimeEl) {
        updateDateTime(lang);
    }
}

/**
 * Update date/time display with locale
 */
function updateDateTime(lang) {
    const datetimeEl = document.getElementById('datetime-display');
    if (!datetimeEl) return;
    const now = new Date();
    const locale = langDateLocale[lang] || 'en-US';
    const options = { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric', hour: 'numeric', minute: '2-digit' };
    datetimeEl.innerText = now.toLocaleDateString(locale, options);
}

/**
 * Initialize i18n on page load
 */
function initI18n() {
    const savedLang = localStorage.getItem('selectedLang') || 'en';

    // Set up language selectors
    document.querySelectorAll('.lang-selector').forEach(sel => {
        sel.value = langCodeToName[savedLang] || 'English';
        sel.addEventListener('change', (e) => {
            const code = langNameToCode[e.target.value] || 'en';
            setLanguage(code);
        });
    });

    // Apply translations
    applyTranslations(savedLang);

    // Update date with locale if present
    const datetimeEl = document.getElementById('datetime-display');
    if (datetimeEl) {
        updateDateTime(savedLang);
        setInterval(() => {
            const lang = localStorage.getItem('selectedLang') || 'en';
            updateDateTime(lang);
        }, 60000);
    }
}

// Run on DOM ready
document.addEventListener('DOMContentLoaded', initI18n);
